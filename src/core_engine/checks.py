"""Deterministic UI predicates; model output is data, never JavaScript."""

import asyncio
from dataclasses import dataclass
import time

from .policy import PolicyError


@dataclass(frozen=True)
class Check:
    kind: str
    selector: str
    value: str
    other_selector: str = ""

    def __post_init__(self):
        if self.kind not in {"text", "visible", "enabled", "count", "overlap", "clipped"}:
            raise ValueError("unsupported UI check")
        if not isinstance(self.selector, str) or not 1 <= len(self.selector) <= 256:
            raise ValueError("invalid check selector")
        if not isinstance(self.value, str) or len(self.value) > 2000:
            raise ValueError("invalid check value")
        if self.kind in {"visible", "enabled", "overlap", "clipped"} and self.value not in {"true", "false"}:
            raise ValueError("boolean checks use true/false")
        if self.kind == "count" and (not self.value.isascii() or not self.value.isdigit() or not 0 <= int(self.value) <= 1000):
            raise ValueError("count must be 0..1000")
        if not isinstance(self.other_selector, str) or len(self.other_selector) > 256:
            raise ValueError("invalid secondary selector")
        if (self.kind == "overlap") != bool(self.other_selector):
            raise ValueError("only overlap requires a secondary selector")


async def observe_check(page, check) -> bool:
    """Missing/ambiguous elements are blocked except explicit visibility/count checks."""
    if not isinstance(check, Check):
        # Legacy TextCheck keeps its visible-element semantics.
        check = Check("text", check.selector, check.text)
    locator = page.locator("css=" + check.selector)
    count = await locator.count()
    if check.kind == "count":
        return count == int(check.value)
    if check.kind == "visible":
        if count > 1:
            raise PolicyError("AMBIGUOUS_CHECK_TARGET")
        visible = count == 1 and await locator.is_visible()
        return visible == (check.value == "true")
    if count != 1 or not await locator.is_visible():
        raise PolicyError("CHECK_TARGET_UNAVAILABLE")
    if check.kind == "text":
        return (await locator.inner_text()).strip() == check.value.strip()
    if check.kind == "enabled":
        actual = await locator.is_enabled()
    elif check.kind == "overlap":
        other = page.locator("css=" + check.other_selector)
        if await other.count() != 1 or not await other.is_visible():
            raise PolicyError("CHECK_TARGET_UNAVAILABLE")
        a, b = await locator.bounding_box(), await other.bounding_box()
        if not a or not b:
            raise PolicyError("CHECK_TARGET_UNAVAILABLE")
        actual = (min(a["x"] + a["width"], b["x"] + b["width"]) - max(a["x"], b["x"]) > 1
                  and min(a["y"] + a["height"], b["y"] + b["height"]) - max(a["y"], b["y"]) > 1)
    else:
        # Fixed, read-only engine code, never generated by the model.
        actual = await locator.evaluate("""el => {
            const r = el.getBoundingClientRect();
            return r.left < -1 || r.top < -1 || r.right > innerWidth + 1 || r.bottom > innerHeight + 1
                || el.scrollWidth > el.clientWidth + 1 || el.scrollHeight > el.clientHeight + 1;
        }""")
    return actual == (check.value == "true")


async def wait_for_check(page, check, timeout_ms, guard):
    deadline = time.monotonic() + timeout_ms / 1000
    while True:
        guard()
        try:
            if await observe_check(page, check):
                return
        except PolicyError as exc:
            if exc.code not in {"CHECK_TARGET_UNAVAILABLE"}:
                raise
        if time.monotonic() >= deadline:
            raise PolicyError("STEP_OR_READINESS_FAILED")
        await asyncio.sleep(0.05)
